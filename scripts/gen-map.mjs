// Generates src/data/worldMap.ts: a dotted world map plus hub coordinates.
// Run once: node scripts/gen-map.mjs  (output is committed)
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoNaturalEarth1, geoContains } from "d3-geo";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);

const W = 1000, H = 500;
const projection = geoNaturalEarth1().fitExtent([[8, 8], [W - 8, H - 8]], { type: "Sphere" });

const step = 9;
const dots = [];
for (let y = 10; y < H - 6; y += step) {
  for (let x = 10 + ((Math.round(y / step) % 2) * step) / 2; x < W - 6; x += step) {
    const p = projection.invert([x, y]);
    if (p && p[1] > -58 && geoContains(land, p)) dots.push([Math.round(x), Math.round(y)]);
  }
}

const hubs = {
  abuja: [7.4913, 9.0579],
  newYork: [-74.006, 40.7128],
  geneva: [6.1432, 46.2044],
  addis: [38.7578, 9.0054],
  brussels: [4.3517, 50.8503],
  nairobi: [36.8219, -1.2921],
};
const pos = Object.fromEntries(
  Object.entries(hubs).map(([k, v]) => {
    const [x, y] = projection(v);
    return [k, [Math.round(x * 10) / 10, Math.round(y * 10) / 10]];
  }),
);

// single SVG path of tiny segments, drawn with round linecaps = dots
const d = dots.map(([x, y]) => `M${x} ${y}h.01`).join("");
writeFileSync(
  "src/data/worldMap.ts",
  `// Generated by scripts/gen-map.mjs. Do not edit by hand.\nexport const WORLD_W = ${W};\nexport const WORLD_H = ${H};\nexport const worldDotsPath = ${JSON.stringify(d)};\nexport const hubs = ${JSON.stringify(pos)} as const;\n`,
);
console.log("dots:", dots.length, "hubs:", JSON.stringify(pos));
